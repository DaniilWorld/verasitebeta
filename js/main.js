const getInitialLanguage = () => {
  const saved = localStorage.getItem("vera-language");
  return saved === "ru" ? "ru" : "en";
};

const createPlatformLink = (platform, className) => {
  const href = linkConfig[platform];
  const link = document.createElement("a");
  link.className = `${className}${href ? "" : " is-disabled"}`;
  link.href = href || "#";
  link.dataset.socialPlatform = platform;
  link.innerHTML = className === "social-icon-link"
    ? `${platformIcons[platform] || ""}<span>${platformNames[platform]}</span>`
    : `${platformIcons[platform] || ""}<span>${platformNames[platform]}</span>`;
  link.setAttribute("aria-label", platformNames[platform]);

  if (!href) {
    link.setAttribute("aria-disabled", "true");
    link.dataset.missingLink = platform;
    link.addEventListener("click", (event) => event.preventDefault());
  } else {
    link.target = "_blank";
    link.rel = "noopener noreferrer";
  }

  return link;
};

const renderPlatformLinks = (container, platforms, className) => {
  if (!container) return;
  container.innerHTML = "";
  platforms.forEach((platform) => container.appendChild(createPlatformLink(platform, className)));
};

const setLanguage = (lang) => {
  const dictionary = translations[lang] || translations.en;
  document.documentElement.lang = lang;
  localStorage.setItem("vera-language", lang);

  document.querySelectorAll("[data-i18n]").forEach((node) => {
    const key = node.dataset.i18n;
    node.innerHTML = dictionary[key] || "";
    node.hidden = dictionary[key] === "";
  });

  document.title = dictionary.documentTitle;

  document.querySelectorAll("[data-i18n-content]").forEach((node) => {
    const key = node.dataset.i18nContent;
    node.setAttribute("content", dictionary[key] || "");
  });

  document.querySelectorAll("[data-i18n-aria-label]").forEach((node) => {
    const key = node.dataset.i18nAriaLabel;
    node.setAttribute("aria-label", dictionary[key] || "");
  });

  document.querySelectorAll("[data-i18n-alt]").forEach((node) => {
    const key = node.dataset.i18nAlt;
    node.setAttribute("alt", dictionary[key] || "");
  });

  document.querySelectorAll("[data-i18n-src]").forEach((node) => {
    const key = node.dataset.i18nSrc;
    node.setAttribute("src", dictionary[key] || "");
  });

  document.querySelectorAll(".lang-btn").forEach((button) => {
    const isActive = button.dataset.lang === lang;
    button.classList.toggle("is-active", isActive);
    button.setAttribute("aria-pressed", String(isActive));
  });

  const social = document.querySelector("[data-social-links]");
  renderPlatformLinks(social, socialSets[lang], "social-icon-link");

  const footerSocial = document.querySelector("[data-footer-social]");
  renderPlatformLinks(footerSocial, footerSocialSets[lang], "footer-social-link");
};

const menuToggle = document.querySelector(".menu-toggle");
const mobileMenu = document.getElementById("mobile-menu");

if (menuToggle && mobileMenu) {
  menuToggle.addEventListener("click", () => {
    const isOpen = menuToggle.getAttribute("aria-expanded") === "true";
    menuToggle.setAttribute("aria-expanded", String(!isOpen));
    mobileMenu.hidden = isOpen;
    document.body.classList.toggle("menu-open", !isOpen);
  });

  mobileMenu.querySelectorAll("a").forEach((link) => {
    link.addEventListener("click", () => {
      menuToggle.setAttribute("aria-expanded", "false");
      mobileMenu.hidden = true;
      document.body.classList.remove("menu-open");
    });
  });
}

document.querySelectorAll(".lang-btn").forEach((button) => {
  button.addEventListener("click", () => setLanguage(button.dataset.lang));
});

document.querySelectorAll("[data-contact-platform]").forEach((link) => {
  const platform = link.dataset.contactPlatform;
  const href = linkConfig[platform];
  const label = link.querySelector("span");
  const icon = link.querySelector(".platform-icon");

  if (icon) icon.innerHTML = platformIcons[platform] || "";
  if (!href) {
    link.href = "#";
    link.classList.add("is-disabled");
    link.setAttribute("aria-disabled", "true");
    link.dataset.missingLink = platform;
    link.addEventListener("click", (event) => event.preventDefault());
  } else {
    link.href = href;
    link.target = "_blank";
    link.rel = "noopener noreferrer";
    link.classList.remove("is-disabled");
    link.removeAttribute("aria-disabled");
    link.removeAttribute("data-missing-link");
  }
});

